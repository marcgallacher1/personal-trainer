// Generates the reference-data migration (muscles + seeded exercise catalogue) from src/lib/seed.
// Reference data lives in a migration (not seed.sql) so `supabase db push` ships it to the hosted DB.
// Usage: node scripts/gen-reference-sql.ts
import { writeFileSync } from 'node:fs'
import { EXERCISES } from '../src/lib/seed/exercises.ts'
import { MUSCLES } from '../src/lib/seed/muscles.ts'
import { seedExerciseId } from './seed-ids.ts'

const OUT = 'supabase/migrations/20261029000100_reference_data.sql'
const q = (s: string): string => `'${s.replaceAll("'", "''")}'`

const lines: string[] = [
  '-- GENERATED by scripts/gen-reference-sql.ts from src/lib/seed. Do not edit by hand.',
  '',
  'insert into public.muscles (id, name, region, body_side, sort_order) values',
  MUSCLES.map(
    (m, i) => `  (${q(m.id)}, ${q(m.name)}, ${q(m.region)}, ${q(m.bodySide)}, ${i})`,
  ).join(',\n') +
    '\non conflict (id) do update set name = excluded.name, region = excluded.region,' +
    ' body_side = excluded.body_side, sort_order = excluded.sort_order;',
  '',
  'insert into public.exercises (id, user_id, name, equipment, pattern, is_compound, is_custom, default_rest_seconds) values',
  EXERCISES.map(
    (e) =>
      `  (${q(seedExerciseId(e.idName ?? e.name))}, null, ${q(e.name)}, ${q(e.equipment)}, ${q(e.pattern)}, ${e.compound}, false, ${e.restSeconds})`,
  ).join(',\n') +
    '\non conflict (id) do update set name = excluded.name, equipment = excluded.equipment, pattern = excluded.pattern,' +
    ' is_compound = excluded.is_compound, default_rest_seconds = excluded.default_rest_seconds;',
  '',
  'insert into public.exercise_muscles (exercise_id, muscle_id, user_id, weight) values',
  EXERCISES.flatMap((e) => [
    ...e.primary.map((m) => `  (${q(seedExerciseId(e.idName ?? e.name))}, ${q(m)}, null, 1.0)`),
    ...e.secondary.map((m) => `  (${q(seedExerciseId(e.idName ?? e.name))}, ${q(m)}, null, 0.5)`),
  ]).join(',\n') + '\non conflict (exercise_id, muscle_id) do update set weight = excluded.weight;',
  '',
]

writeFileSync(OUT, lines.join('\n'))
console.log(`Wrote ${OUT}: ${MUSCLES.length} muscles, ${EXERCISES.length} exercises`)

// Logging types arrived after the reference data shipped, so they live in their own migration
// (a new column + per-exercise values). Regenerated from the same catalogue.
const LOG_TYPES_OUT = 'supabase/migrations/20261030040000_exercise_log_types.sql'
const special = EXERCISES.filter((e) => e.logType !== 'weight_reps')
const logTypeLines = [
  '-- GENERATED by scripts/gen-reference-sql.ts from src/lib/seed. Do not edit by hand.',
  '-- How each exercise is logged, plus timed sets.',
  '',
  "alter table public.exercises add column log_type text not null default 'weight_reps'",
  "  check (log_type in ('weight_reps', 'bodyweight_reps', 'assisted_reps', 'duration', 'weight_duration'));",
  '',
  'alter table public.sets add column duration_seconds int check (duration_seconds >= 0 and duration_seconds <= 86400);',
  '',
  ...special.map(
    (e) =>
      `update public.exercises set log_type = ${q(e.logType)} where id = ${q(seedExerciseId(e.idName ?? e.name))};`,
  ),
  '',
]
writeFileSync(LOG_TYPES_OUT, logTypeLines.join('\n'))
console.log(`Wrote ${LOG_TYPES_OUT}: ${special.length} non-default log types`)
