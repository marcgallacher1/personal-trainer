// Copies the pure notification logic into supabase/functions/_shared so the Edge Functions run
// the exact code the tests cover. Deno needs `.ts` on imports, so they're added here.
// Usage: node scripts/gen-shared.ts (CI fails if the copy is out of date)
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const OUT = 'supabase/functions/_shared/lib'
const FILES = [
  ...readdirSync('src/lib/notify')
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))
    .map((f) => `notify/${f}`),
  'time/london.ts',
]

rmSync(OUT, { recursive: true, force: true })
for (const f of FILES) {
  const src = readFileSync(join('src/lib', f), 'utf8').replace(
    /from '(\.{1,2}\/[^']+)'/g,
    (_m, p: string) => `from '${p}.ts'`,
  )
  mkdirSync(dirname(join(OUT, f)), { recursive: true })
  writeFileSync(
    join(OUT, f),
    `// GENERATED by scripts/gen-shared.ts from src/lib. Do not edit.\n${src}`,
  )
}
console.log(`Wrote ${FILES.length} files to ${OUT}`)
